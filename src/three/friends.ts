type V3 = [number, number, number];
const geo = (g: Part['g'], p: V3, c: string, rot?: V3, sc?: V3): Part => ({ k: 'geo', g, p, s: [1, 1, 1], c, rot, sc });
const eye = (x: number, y: number, z: number, r = 0.03): Part => ({ k: 'sph', p: [x, y, z], s: [r, r * 1.1, r * 0.8], c: '#1E1E24', seg: 8 });
const leg = (x: number, y: number, z: number, r: number, len: number, c: string, foot: string): Part[] => [
  { k: 'caps', p: [x, y, z], s: [r, len, 0], c, seg: 10 },
  { k: 'sph', p: [x, 0.03, z + r * 0.4], s: [r * 1.15, 0.045, r * 1.5], c: foot },
];

